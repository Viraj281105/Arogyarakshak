"""
Hindi / Marathi terminology audit (#37) — the mechanical half of a language QA pass.

    python scripts/terminology_audit.py                    # summary to the terminal
    python scripts/terminology_audit.py --markdown out.md  # + a reviewer worksheet
    python scripts/terminology_audit.py --json out.json

Reads every hi/mr/en string in the app's copy dictionaries (web, mobile, shared i18n) through
Node + tsx (scripts/terminology/dump_ts_copy.mjs), renders the BimaNyay appeal letters and
reads BillNyay's offline fallback letters, and reports what a machine can find: spelling
variants, one concept with two terms, Hindi/Marathi leakage, untranslated English, placeholder
mismatches. It does not decide what is correct and it is not a translation review — a native
speaker must settle every item it lists. Offline; no network, no LLM.
"""

import argparse
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "apps" / "api"))

from app.evaluation.terminology import Entry, audit  # noqa: E402

GLOSSARY = ROOT / "data" / "terminology" / "glossary.json"
# User-supplied fields are Devanagari on purpose: any English left in a generated letter is then
# system-generated text (the audit's grounds and statute names), which is what we want to find.
SAMPLE_DENIAL = {
    "hi": {"insurer_name": "सिंथेटिक बीमा लिमिटेड", "diagnosis": "उच्च रक्तचाप संकट",
           "denial_reason_raw": "प्रस्ताव के समय उच्च रक्तचाप की जानकारी छिपाई गई"},
    "mr": {"insurer_name": "सिंथेटिक विमा लिमिटेड", "diagnosis": "उच्च रक्तदाब संकट",
           "denial_reason_raw": "प्रस्तावाच्या वेळी उच्च रक्तदाबाची माहिती लपवली"},
}
SAMPLE_COMMON = {"policy_number": "SYN-0001", "policy_age_years": 6.0, "claimed_amount": 100000.0,
                 "denied_or_deducted_amount": 60000.0, "denial_category": "PED_NON_DISCLOSURE"}


def load_copy():
    out = subprocess.run(["node", "--import", "tsx", str(ROOT / "scripts" / "terminology" / "dump_ts_copy.mjs")],
                         cwd=ROOT, capture_output=True, text=True, check=True, encoding="utf-8")
    return json.loads(out.stdout)


def load_letters():
    """The generated appeal letters, as extra hi/mr entries (one entry per document)."""
    from bimanyay import ClaimDenialInput, analyze_insurance_denial

    from app.services.billnyay_llm import _FALLBACK_APPEAL_LETTERS

    entries = []
    for lang in ("hi", "mr"):
        res = analyze_insurance_denial(ClaimDenialInput(**SAMPLE_COMMON, **SAMPLE_DENIAL[lang]), language=lang)
        for name, text in (("gro_appeal", res.level_1_gro_appeal), ("bimabharosa", res.level_2_bimabharosa_text),
                           ("ombudsman", res.level_3_ombudsman_grounds)):
            entries.append(Entry("letters/bimanyay", name, lang, text))
        entries.append(Entry("letters/billnyay_fallback", "appeal", lang, _FALLBACK_APPEAL_LETTERS[lang]))
    return entries


def _where(examples, n=2):
    return "; ".join(f"{e[0]}:{e[1]}" for e in examples[:n])


def markdown(report) -> str:
    lines = ["# Hindi / Marathi terminology audit", "",
             "> Generated by `scripts/terminology_audit.py`. **Mechanical findings only, for a native-speaker "
             "reviewer to settle.** Nothing here says a term is wrong; the glossary behind it "
             "(`data/terminology/glossary.json`) is UNREVIEWED and written by the engineering team.", "",
             f"Strings read: {report['strings']}", ""]
    lines += ["## Concepts rendered with more than one term in the same language", "",
              "| Concept | Language | Terms in use (count) | Where | Reviewer decision |", "|---|---|---|---|---|"]
    for c in report["glossary_conflicts"]:
        terms = ", ".join(f"{t} ({c['variants_in_use'][t]['count']})" for t in c["distinct_terms"])
        ex = _where([e for t in c["distinct_terms"] for e in c["variants_in_use"][t]["examples"][:1]], 3)
        lines.append(f"| {c['concept']} ({c['english']}) | {c['lang']} | {terms} | {ex} |  |")
    lines += ["", "## Spelling variants of the same word", "", "| Language | Forms (count) | Where | Reviewer decision |", "|---|---|---|---|"]
    for v in report["spelling_variants"]:
        lines.append(f"| {v['lang']} | {', '.join(f'{f} ({n})' for f, n in v['forms'].items())} | {_where(v['examples'])} |  |")
    lines += ["", "## Words from the other language", "", "| Language | Kind | Words | Where |", "|---|---|---|---|"]
    for v in report["language_leakage"]:
        lines.append(f"| {v['lang']} | {v['kind']} | {', '.join(v['words'])} | {v['source']}:{v['key']} |")
    lines += ["", "## Latin-script words left in Hindi/Marathi text (outside the allow-list)", "", "| Word | Count | Where |", "|---|---|---|"]
    for w, d in report["english_words"].items():
        lines.append(f"| {w} | {d['count']} | {_where([(e[0], f'{e[1]} ({e[2]})') for e in d['examples']])} |")
    lines += ["", "## Hindi/Marathi text identical to the English source", "", "| Language | Where | Text |", "|---|---|---|"]
    for u in report["untranslated"]:
        lines.append(f"| {u['lang']} | {u['source']}:{u['key']} | {u['text'][:60]} |")
    lines += ["", f"## Placeholder mismatches: {len(report['placeholder_mismatch'])}", ""]
    for m in report["placeholder_mismatch"]:
        lines.append(f"- {m['lang']} {m['source']}:{m['key']}: English {m['english']} vs {m[m['lang']]}")
    return "\n".join(lines) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--markdown", type=Path)
    ap.add_argument("--json", type=Path)
    args = ap.parse_args(argv)

    report = audit(load_copy(), json.loads(GLOSSARY.read_text(encoding="utf-8")), load_letters())
    print(f"strings: {report['strings']}")
    print(f"concepts with more than one term in a language: {len(report['glossary_conflicts'])}")
    for c in report["glossary_conflicts"]:
        print(f"  - {c['concept']} [{c['lang']}]: " + ", ".join(f"{t} x{c['variants_in_use'][t]['count']}" for t in c["distinct_terms"]))
    print(f"spelling variants: {len(report['spelling_variants'])}")
    for v in report["spelling_variants"]:
        print(f"  - [{v['lang']}] " + ", ".join(f"{f} x{n}" for f, n in v["forms"].items()))
    print(f"language leakage: {len(report['language_leakage'])}   untranslated: {len(report['untranslated'])}   "
          f"placeholder mismatches: {len(report['placeholder_mismatch'])}   English words: {len(report['english_words'])}")
    if args.markdown:
        args.markdown.write_text(markdown(report), encoding="utf-8")
    if args.json:
        args.json.write_text(json.dumps(report, ensure_ascii=False, indent=2), encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
