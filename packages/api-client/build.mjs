// API-client generator. Types come from docs/api/openapi.json (the committed, test-guarded
// contract exported by scripts/export_openapi.py); src/ is then vendored into both apps.
// Usage: node packages/api-client/build.mjs [--check]
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";
import { syncShared } from "../../scripts/sync-shared.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(here, "..", "..");
const BANNER = "// GENERATED - do not edit; source: packages/api-client/src";

export const defaultPaths = {
  specPath: join(repoRoot, "docs", "api", "openapi.json"),
  schemaPath: join(here, "src", "generated", "schema.d.ts"),
  srcDir: join(here, "src"),
  targets: [
    join(repoRoot, "apps", "web", "app", "shared", "api-client"),
    join(repoRoot, "apps", "mobile", "src", "shared", "api-client"),
  ],
};

/** schema.d.ts content for the given OpenAPI spec file. */
export async function buildSchema(specPath = defaultPaths.specPath) {
  const ast = await openapiTS(pathToFileURL(specPath));
  return `// Generated by openapi-typescript from docs/api/openapi.json - do not edit.\n${astToString(ast)}`;
}

/** Regenerate schema.d.ts and vendor src/. In check mode nothing is written; throws listing stale files. */
export async function runBuild({ check = false, paths = defaultPaths } = {}) {
  const stale = [];
  const schema = await buildSchema(paths.specPath);
  const current = existsSync(paths.schemaPath) ? readFileSync(paths.schemaPath, "utf8") : null;
  if (current !== schema) {
    stale.push(paths.schemaPath);
    if (!check) {
      mkdirSync(dirname(paths.schemaPath), { recursive: true });
      writeFileSync(paths.schemaPath, schema);
    }
  }
  const { changed } = syncShared({ from: paths.srcDir, to: paths.targets, banner: BANNER, check });
  stale.push(...changed);
  if (check && stale.length > 0) {
    throw new Error(`api-client is stale; run \`npm run generate\`:\n${stale.map((f) => `  ${f}`).join("\n")}`);
  }
  return { changed: stale };
}
