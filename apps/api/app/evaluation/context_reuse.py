"""Context hit rate and duplicate-processing reduction (DPR) for Kadi's shared case context (#112).

What is and is not measured (fixed before measuring):

- A **context request** is a read of a case's stored context through
  ``app.services.case_context.load_case_entities`` (Phase 4 decision D8). Outcome ``served``:
  the case held at least one item for it; ``empty``: it held nothing.
- **Context hit rate** = served / all requests. It measures *non-emptiness*, not reuse: modules
  never re-extract, so a read of a populated case is served by construction and the rate is
  close to 1. It is reported for transparency, **never gated**, and covers only the
  instrumented readers (the ones listed in ``docs/evaluation/context-reuse.md``).
- **DPR** (duplicate-processing reduction) is a *modelled* figure, not a measured one:

      current_work  = ingest_work                                   (what the pipeline does)
      baseline_work = ingest_work + requests x documents x WORK_UNITS_PER_READ
      DPR           = (baseline_work - current_work) / baseline_work

  The baseline is a design in which every context read re-runs OCR and extraction over every
  document of the case instead of reading stored entities. Nothing is re-run to get it: the
  documents are gone after ingestion (zero retention), so ``documents`` is passed in as data.

The scorer is pure arithmetic on explicit counts. The counts come from the instrumented pipeline
run over the synthetic demo scenarios A-E (``data/evaluation/context_reuse_synthetic.jsonl``,
generated by ``scripts/generate_context_reuse_dataset.py``); they are counts on synthetic
scenarios, not production traffic, and say nothing about extraction quality.

Row shape::

    {"id": "A", "documents": 2,
     "ingest": {"ocr": 2, "extraction": 2},
     "requests": {"billnyay": {"served": 7, "empty": 0}}}
"""

from collections import defaultdict
from typing import Any, Dict, List, Optional

from app.evaluation.metrics import safe_div

WORK_UNITS_PER_READ = 2  # one OCR pass + one extraction pass over each document


def _count(value: Any, where: str) -> int:
    if isinstance(value, bool) or not isinstance(value, int) or value < 0:
        raise ValueError(f"{where}: counts must be non-negative integers, got {value!r}")
    return value


def _requests(row: Dict[str, Any], sid: str) -> Dict[str, Dict[str, int]]:
    out: Dict[str, Dict[str, int]] = {}
    for module, outcomes in (row.get("requests") or {}).items():
        unknown = set(outcomes) - {"served", "empty"}
        if unknown:
            raise ValueError(f"{sid}: unknown outcome(s) {sorted(unknown)} for {module}")
        out[module] = {o: _count(outcomes.get(o, 0), f"{sid}.{module}.{o}") for o in ("served", "empty")}
    return out


def _round(value: Optional[float]) -> Optional[float]:
    return None if value is None else round(value, 4)


def evaluate_context_reuse(scenarios: List[Dict[str, Any]]) -> Dict[str, Any]:
    per_scenario: List[Dict[str, Any]] = []
    module_served: Dict[str, int] = defaultdict(int)
    module_total: Dict[str, int] = defaultdict(int)
    served = requests = current = baseline = 0
    for row in scenarios:
        sid = str(row.get("id"))
        by_module = _requests(row, sid)
        documents = _count(row.get("documents"), f"{sid}.documents")
        ingest = sum(_count(v, f"{sid}.ingest.{k}") for k, v in (row.get("ingest") or {}).items())
        s_served = sum(v["served"] for v in by_module.values())
        s_requests = sum(v["served"] + v["empty"] for v in by_module.values())
        s_current = ingest
        s_baseline = ingest + s_requests * documents * WORK_UNITS_PER_READ
        for module, v in by_module.items():
            module_served[module] += v["served"]
            module_total[module] += v["served"] + v["empty"]
        per_scenario.append({
            "id": sid, "requests": s_requests, "served": s_served,
            "hit_rate": _round(safe_div(s_served, s_requests)),
            "current_work": s_current, "baseline_work": s_baseline,
            "dpr": _round(safe_div(s_baseline - s_current, s_baseline)),
        })
        served += s_served
        requests += s_requests
        current += s_current
        baseline += s_baseline
    return {
        "n_scenarios": len(scenarios),
        "n_requests": requests,
        "served": served,
        "hit_rate": _round(safe_div(served, requests)),
        "current_work": current,
        "baseline_work": baseline,
        "dpr": _round(safe_div(baseline - current, baseline)),
        "per_module_hit_rate": {m: _round(safe_div(module_served[m], module_total[m])) for m in sorted(module_total)},
        "per_scenario": per_scenario,
    }
