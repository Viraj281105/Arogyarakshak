"""Builds the retrieval gold corpus from the clean in-repo modules it quotes.

``data/evaluation/retrieval_corpus_synthetic.jsonl`` is a frozen copy of ``build_corpus_rows()``;
``tests/test_evaluation_retrieval.py`` fails when they differ, so a wording change in
SchemeSetu / BimaNyay / DaaviSetu is noticed (labels in the queries file must then be re-checked).
Regenerate with ``python -m app.evaluation.retrieval_corpus`` from ``apps/api``.

Relationship to the sources: SchemeSetu, DaaviSetu, clinical_triggers and tracker passages are
verbatim strings or docstring paragraphs. BimaNyay clause passages are the real output of
``audit_claim_denial`` / ``draft_gro_appeal_letter`` for fixed synthetic inputs (policy age,
diagnosis and amounts below are invented). English only. The downloaded Marathi/Hindi PDFs have
corrupted text layers and are not used.
"""

import json
import re
import sys
from pathlib import Path
from typing import Any, Dict, List, Tuple

T = "schemesetu.thresholds"
C = "bimanyay.clause_auditor"
D = "bimanyay.drafter"
K = "bimanyay.clinical_triggers"
R = "bimanyay.tracker"
V = "daavisetu.readiness"

CORPUS_META = {
    "name": "retrieval_corpus_synthetic_v2",
    "synthetic": True,
    "provenance": (
        "27 clean in-repo English passages generated by app/evaluation/retrieval_corpus.py from "
        "packages/schemesetu/schemesetu/thresholds.py (criteria text and its cited-source summaries), "
        "packages/bimanyay (clause_auditor and drafter output for fixed invented inputs, "
        "clinical_triggers, tracker) and packages/daavisetu/daavisetu/readiness.py. A test fails when the "
        "file no longer equals what the modules produce. NOT the downloaded Marathi/Hindi PDFs, whose text "
        "layers are corrupted. English only: no Devanagari corpus text is measured. page is the passage "
        "number within its source module, not a PDF page."
    ),
    "description": "Passages the retrieval gold queries are labelled against; key = '<source>#<page>'.",
}


def _para(doc: str, startswith: str) -> str:
    for p in re.split(r"\n\s*\n", doc):
        if p.strip().startswith(startswith):
            return p.strip()
    raise KeyError(startswith)


def _violation_para(v: Any) -> str:
    return f"{v.clause_reference}. {v.violation_summary} {v.legal_remedy}"


def _denial(category: str, age: float, reason: str, diagnosis: str) -> Tuple[Any, str, List[Any]]:
    from bimanyay import ClaimDenialInput, audit_claim_denial

    data = ClaimDenialInput(
        policy_number="SYN-RET-0001",
        insurer_name="Synthetic Insurer Ltd",
        policy_age_years=age,
        claimed_amount=100000.0,
        denied_or_deducted_amount=60000.0,
        denial_category=category,
        denial_reason_raw=reason,
        diagnosis=diagnosis,
    )
    _w, _p, grounds, violations = audit_claim_denial(data)
    return data, grounds, violations


def build_corpus_rows() -> List[Dict[str, Any]]:
    import bimanyay.clinical_triggers as ct
    import bimanyay.tracker as tracker
    import daavisetu.readiness as readiness
    import schemesetu.thresholds as th
    from bimanyay import draft_gro_appeal_letter

    def cite(c: Any) -> str:
        return f"{c.document}. {c.supports}"

    doc = th.__doc__ or ""
    passages: List[Tuple[str, int, str]] = [
        (T, 1, th.PMJAY.official_basis),
        (T, 2, cite(th.PMJAY.citations[0])),
        (T, 3, cite(th.PMJAY.citations[1])),
        (T, 4, "\n\n".join(th.PMJAY.verification_steps)),
        (T, 5, th.MJPJAY.official_basis),
        (T, 6, cite(th.MJPJAY.citations[0])),
        (T, 7, cite(th.MJPJAY.citations[1])),
        (T, 8, "\n\n".join(th.MJPJAY.verification_steps)),
        (T, 9, th.MJPJAY.verification_gaps[0]),
        (T, 10, _para(doc, "Income is a NON-DETERMINATIVE")),
        (T, 11, _para(doc, "- AB PM-JAY")),
        (T, 12, _para(doc, "Sources were retrieved")),
    ]
    _d1, g1, v1 = _denial("PED_NON_DISCLOSURE", 6.0, "Hypertension not disclosed at proposal stage", "Hypertensive crisis")
    _d2, g2, v2 = _denial("PED_NON_DISCLOSURE", 2.0, "Diabetes found to be pre-existing", "Diabetic ketoacidosis")
    _d3, g3, v3 = _denial("INVESTIGATION_ONLY", 1.0, "Admission was for investigation only", "Dengue fever")
    _d4, g4, v4 = _denial("ROOM_RENT_CAPPING", 1.0, "Proportionate deduction applied", "Appendicitis")
    d5, g5, v5 = _denial("DELAYED_INTIMATION", 1.0, "Claim intimated late", "Fracture of femur")
    passages += [
        (C, 1, g1 + "\n\n" + _violation_para(v1[0])),
        (C, 2, g2),
        (C, 3, g3 + "\n\n" + _violation_para(v3[0])),
        (C, 4, g4 + "\n\n" + _violation_para(v4[0])),
        (C, 5, g5 + "\n\n" + _violation_para(v5[0])),
        (C, 6, _violation_para(v4[-1])),
    ]
    letter = draft_gro_appeal_letter(d5, g5, v5, language="en")
    passages.append((D, 1, _para(letter, "Under the IRDAI Master Circular on Health Insurance Business") + "\n\n"
                     + _para(letter, "I request you to re-examine")))
    passages += [
        (K, 1, (ct.__doc__ or "").strip()),
        (K, 2, ct.CLINICAL_DENIAL_CATEGORIES["INVESTIGATION_ONLY"]),
        (K, 3, ct.CLINICAL_DENIAL_CATEGORIES["PED_NON_DISCLOSURE"]),
        (R, 1, (tracker.__doc__ or "").strip().split("\n\n", 1)[1]),
        (R, 2, tracker._SRC_OMBUDSMAN),
        (V, 1, (readiness.__doc__ or "").strip()),
        (V, 2, readiness.BASELINE_SOURCE),
        (V, 3, readiness.READINESS_DISCLAIMER),
    ]
    return [
        {"id": f"DOC-{i:03d}", "source": s, "page": p, "text": text}
        for i, (s, p, text) in enumerate(passages, 1)
    ]


def corpus_lines() -> List[str]:
    lines = [json.dumps({"_meta": CORPUS_META}, ensure_ascii=False)]
    lines += [json.dumps(row, ensure_ascii=False) for row in build_corpus_rows()]
    return lines


if __name__ == "__main__":
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).resolve().parents[4] / "data" / "evaluation"
    (out / "retrieval_corpus_synthetic.jsonl").write_text("\n".join(corpus_lines()) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {len(corpus_lines()) - 1} passages to {out}")
