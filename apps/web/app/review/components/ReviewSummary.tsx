"use client";

import React from "react";
import { COI_OPTIONS } from "../../lib/clinical";
import { TONE_CLASS, formatTimestamp, humanizeEnum } from "../../lib/labels";
import { MODULE_LABEL, ReviewerDetail, TRIGGER_LABEL } from "../types";
import { useT } from "../../i18n/useT";

/** What the review is about, why it was routed here, and — while it is only assigned —
 *  the conflict-of-interest declaration that must precede any evidence. */
export function ReviewSummary({
  detail,
  coi,
  setCoi,
  onAccept,
  onDecline,
}: {
  detail: ReviewerDetail;
  coi: { category: string; disclosure: string };
  setCoi: (value: { category: string; disclosure: string }) => void;
  onAccept: () => void;
  onDecline: () => void;
}) {
  const tr = useT();
  return (
    <>
      <h3 id="review-detail">
        {detail.review_type === "FACT_CONFIRMATION" ? tr("Confirm clinical facts") : tr("Clinical statement request")}
      </h3>
      <dl style={{ display: "grid", gridTemplateColumns: "minmax(8rem, max-content) 1fr", gap: "0.25rem 1rem", fontSize: "0.85rem" }}>
        <dt className="stat-label">{tr("Case context")}</dt>
        <dd>{tr(MODULE_LABEL[detail.source_module] ?? humanizeEnum(detail.source_module))}</dd>
        <dt className="stat-label">{tr("Why it was routed to you")}</dt>
        <dd>{tr(TRIGGER_LABEL[detail.trigger ?? ""] ?? humanizeEnum(detail.trigger))}</dd>
        <dt className="stat-label">{tr("Status")}</dt>
        <dd>
          <span className={TONE_CLASS.neutral}>{tr(humanizeEnum(detail.status))}</span>
        </dd>
        <dt className="stat-label">{tr("Conflict of interest")}</dt>
        <dd>
          {detail.coi_label ? (
            <>
              <span className={TONE_CLASS.success}>{tr("Declared")}</span> {detail.coi_label}
              {detail.coi_disclosure ? ` — ${detail.coi_disclosure}` : ""}
            </>
          ) : (
            <span className={TONE_CLASS.warning}>{tr("Not yet declared — required before evidence opens")}</span>
          )}
        </dd>
        <dt className="stat-label">{tr("Evidence shared")}</dt>
        <dd>{(detail.evidence_scope ?? []).map(humanizeEnum).join(", ") || "—"}{" "}{tr("(chosen by the patient)")}</dd>
        {detail.created_at && (
          <>
            <dt className="stat-label">{tr("Requested")}</dt>
            <dd>{formatTimestamp(detail.created_at)}</dd>
          </>
        )}
      </dl>
      <div style={{ marginTop: "0.75rem" }}>
        <div className="stat-label">{tr("Question put to you")}{" "}<span className={TONE_CLASS.machine}>{tr("⚙ Generated by ArogyaRakshak")}</span>
        </div>
        <p>{detail.clinical_question}</p>
      </div>

      {detail.status === "ASSIGNED" && (
        <div>
          <p style={{ fontSize: "0.9rem" }}>{tr("Before you see any clinical evidence, declare your relationship to this case. Hospital:")}{" "}
            {detail.coi_context.hospital_names.join(", ") || tr("not stated")}{" "}{tr("· Insurer:")}{" "}{detail.coi_context.insurer_name ?? tr("not stated")}
          </p>
          <select className="select-field" aria-label={tr("Conflict of interest")} value={coi.category} onChange={(e) => setCoi({ ...coi, category: e.target.value })}>
            <option value="">{tr("Declare conflict of interest…")}</option>
            {COI_OPTIONS.map((o) => (
              <option key={o.value} value={o.value}>
                {tr(o.label)}
              </option>
            ))}
          </select>
          <textarea
            className="textarea-field"
            placeholder={tr("Disclosure details (required for 'Other')")}
            value={coi.disclosure}
            onChange={(e) => setCoi({ ...coi, disclosure: e.target.value })}
          />
          <div style={{ display: "flex", gap: "0.5rem", marginTop: "0.5rem" }}>
            <button type="button" className="btn btn-primary" disabled={!coi.category} onClick={onAccept}>{tr("Accept review")}</button>
            <button type="button" className="btn" style={{ border: "1px solid var(--border-subtle)" }} onClick={onDecline}>{tr("Decline")}</button>
          </div>
        </div>
      )}
    </>
  );
}
