"""Generates the ``kyverno test`` set from the shared fixture corpus (``fixtures/``).

    python infrastructure/policy/build_kyverno_tests.py          # rewrite kyverno-tests/
    python infrastructure/policy/build_kyverno_tests.py --check  # exit 1 if kyverno-tests/ is stale

Every Kubernetes fixture becomes a Pod in namespace ``arogyarakshak`` (the namespace the policies
are scoped to). A bad fixture must FAIL the Kyverno rules it lists in ``kyverno_rules`` (default:
every rule of the policy named in ``rule``) and PASS every other rule; a good fixture passes all.
Compose fixtures are not Kubernetes objects and are covered by the Rego and Python checks only.
NOT EXECUTED here: `kyverno test infrastructure/policy/kyverno-tests` needs the Kyverno CLI.
"""

from __future__ import annotations

import pathlib
import sys
from typing import Any, Dict, List, Tuple

import yaml

HERE = pathlib.Path(__file__).resolve().parent
FIXTURES = HERE / "fixtures"
POLICIES = HERE / "kyverno"
OUT = HERE / "kyverno-tests"
NAMESPACE = "arogyarakshak"


def _pod_spec(obj: Dict[str, Any]) -> Dict[str, Any]:
    kind = obj["kind"]
    if kind == "Pod":
        return obj["spec"]
    if kind == "CronJob":
        return obj["spec"]["jobTemplate"]["spec"]["template"]["spec"]
    return obj["spec"]["template"]["spec"]


def load_fixtures() -> List[Tuple[str, str, Dict[str, Any]]]:
    """(name, 'good'|'bad', document) for every Kubernetes fixture, sorted."""
    out = []
    for verdict in ("good", "bad"):
        for path in sorted((FIXTURES / verdict).glob("*.yaml")):
            doc = yaml.safe_load(path.read_text(encoding="utf-8"))
            if doc["kind"] == "k8s":
                out.append((path.stem.replace("_", "-"), verdict, doc))
    return out


def policy_rules() -> Dict[str, List[str]]:
    rules = {}
    for path in sorted(POLICIES.glob("*.yaml")):
        doc = yaml.safe_load(path.read_text(encoding="utf-8"))
        rules[doc["metadata"]["name"]] = [r["name"] for r in doc["spec"]["rules"]]
    return rules


def build() -> Dict[str, str]:
    fixtures = load_fixtures()
    resources = [
        {"apiVersion": "v1", "kind": "Pod",
         "metadata": {"name": name, "namespace": NAMESPACE},
         "spec": _pod_spec(doc["object"])}
        for name, _verdict, doc in fixtures
    ]
    results = []
    for policy, rule_names in policy_rules().items():
        for rule in rule_names:
            failing, passing = [], []
            for name, verdict, doc in fixtures:
                if verdict == "bad":
                    targets = doc.get("kyverno_rules") or policy_rules()[doc["rule"]]
                    fails = doc["rule"] == policy and rule in targets
                else:
                    fails = False
                (failing if fails else passing).append(name)
            for outcome, names in (("fail", failing), ("pass", passing)):
                if names:
                    results.append({"policy": policy, "rule": rule, "resources": names, "kind": "Pod", "result": outcome})
    test = {
        "apiVersion": "cli.kyverno.io/v1alpha1",
        "kind": "Test",
        "metadata": {"name": "arogyarakshak-pod-policies"},
        "policies": [f"../kyverno/{p.name}" for p in sorted(POLICIES.glob("*.yaml"))],
        "resources": ["resources.yaml"],
        "results": results,
    }
    header = "# GENERATED by infrastructure/policy/build_kyverno_tests.py from fixtures/ - do not edit.\n"
    return {
        "kyverno-test.yaml": header + yaml.safe_dump(test, sort_keys=False, width=110),
        "resources.yaml": header + yaml.safe_dump_all(resources, sort_keys=False, width=110),
    }


def main(argv: List[str]) -> int:
    files = build()
    if "--check" in argv:
        stale = [n for n, text in files.items()
                 if not (OUT / n).exists() or (OUT / n).read_text(encoding="utf-8") != text]
        for n in stale:
            print(f"stale: {OUT / n}")
        return 1 if stale else 0
    OUT.mkdir(exist_ok=True)
    for name, text in files.items():
        (OUT / name).write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
